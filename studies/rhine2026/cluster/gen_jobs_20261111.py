r"""Job lists of the batch of 11 November 2026: the runs that read the 2026 profile, rerun on the season as observed.

The lines are those of the lists of 2 November (jobs_20261102_*.txt), flags unchanged, so that only the gauge profile
differs from the batch of 2 November: scenarios/2026.csv is now the river as observed to 10 November 2026 with the
forecasts of the Federal Institute of Hydrology for the days after, and the wave profiles are rebuilt from it
(build_wave_profiles.py). The runs of 2018 are not rerun, with one exception (below).

Two lists:
  jobs_20261111_ref.txt     the reference network (cache tmp/r6cal): a two-week run that builds the caches, named *_base
                            so that the launcher chains every other run on it; the reference run; the 2026 lines of the
                            main, sensitivity, crossed and no-rail lists, without the two stress paths on the outlook's
                            quartiles; a control run on the profile of 30 September (2026_vintage0930), which must
                            return the loss of 2 November to the last digit; and the 2018 run at 0.75 times the
                            inventories, which on 6 November ran on later model code than the other runs.
  jobs_20261111_paired.txt  the ten further networks: for each seed a base that builds tmp/r6bc_seedN and five levers
                            chained on it (launch WITHOUT --independent).

Launched from a separate checkout on the cluster (/projects/disruptsc/disrupt-sc-rhine: the study scripts of commit
9ff8c8f with src/ and config/ of d72aa00, the model code of the batch of 2 November), outputs in
/projects/disruptsc/runs/rhine2026_obs, so that nothing of the batch of 2 November is overwritten.

    python studies/rhine2026/cluster/gen_jobs_20261111.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def lines(name: str) -> list[tuple[str, str]]:
    out = []
    for ln in (HERE / name).read_text(encoding="utf-8").splitlines():
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        run, flags = ln.split("|", 1)
        out.append((run.strip(), flags.strip()))
    return out


def fmt(rows: list[tuple[str, str]]) -> str:
    w = max(len(r) for r, _ in rows)
    return "\n".join(f"{r:<{w}} | {f}" for r, f in rows) + "\n"


ref = lines("jobs_20261102_2026_bycargo.txt")
assert [r for r, _ in ref] == ["2026_r6_bycargo"], ref
ref_flags = ref[0][1]
assert ref_flags.endswith("--cache-dir r6cal"), ref_flags

keep_2026 = lambda rows: [(r, f) for r, f in rows if r.startswith(("2026_", "wave_"))]      # noqa: E731
main = keep_2026(lines("jobs_20261102_main.txt"))
rev = [(r, f) for r, f in keep_2026(lines("jobs_20261102_rev.txt")) if not r.endswith(("_q25", "_q75"))]
cross = keep_2026(lines("jobs_20261102_cross.txt"))
norail = keep_2026(lines("jobs_20261102_norail.txt"))
inv075 = lines("jobs_20261106_inv075.txt")
assert (len(main), len(rev), len(cross), len(norail), len(inv075)) == (19, 12, 8, 1, 1), (len(main), len(rev), len(cross), len(norail), len(inv075))

builder = ("cachebuild_r6cal_base", f"--profile smoke2w {ref_flags.replace('--recovery-weeks 20', '--recovery-weeks 0')}")
control = ("2026_r6_bycargo_profile0930", f"--profile 2026_vintage0930 {ref_flags}")
rows_ref = [builder] + ref + main + rev + cross + norail + [control] + inv075
names = [r for r, _ in rows_ref]
assert len(names) == len(set(names)) == 44, len(names)

HEAD_REF = """# Rhine 2026 cluster batch (11 Nov 2026): the runs of the REFERENCE NETWORK on the season as observed.
# scenarios/2026.csv = the Kaub gauge observed to 10 November 2026 (PEGELONLINE), the BfG forecasts for the days after
# (14-day forecast of 11 November to 22 November, six-week outlook of 9 November for the last week); the wave profiles
# are rebuilt from it. Flags unchanged from the lists of 2 November (jobs_20261102_2026_bycargo, _main, _rev, _cross,
# _norail), without the two stress paths (q25, q75). Model code of 2 November (src/ and config/ of d72aa00), launched from
# the separate checkout /projects/disruptsc/disrupt-sc-rhine, outputs in /projects/disruptsc/runs/rhine2026_obs.
#   cachebuild_r6cal_base         two weeks on the smoke profile: builds tmp/r6cal; every run below waits for it (afterok)
#   2026_r6_bycargo_profile0930   CONTROL: the reference run on the profile of 30 September (scenarios/2026_vintage0930.csv);
#                                 it must return the German loss of the batch of 2 November (1.110 % of a quarter) exactly
#   2018_r6_bycargo_inv075        the 2018 run at 0.75 times the inventories, repeated on this model code (on 6 November it
#                                 ran on the cluster's later code, which carries the fixes KI-47, KI-50, KI-53 and KI-54)
# Generated by gen_jobs_20261111.py.
#     bash studies/rhine2026/cluster/launch_rhine_batch.sh --jobs studies/rhine2026/cluster/jobs_20261111_ref.txt
#     bash studies/rhine2026/cluster/pack_results.sh --jobs studies/rhine2026/cluster/jobs_20261111_ref.txt --with-firms <names>
#
"""
(HERE / "jobs_20261111_ref.txt").write_text(HEAD_REF + fmt(rows_ref), encoding="utf-8", newline="\n")

paired = lines("jobs_20261102_paired.txt")
assert len(paired) == 60 and all(r.startswith("2026_r6_bycargo_seed") for r, _ in paired)
HEAD_PAIRED = """# Rhine 2026 cluster batch (11 Nov 2026): the PAIRED lever ensemble on the season as observed, the lines of
# jobs_20261102_paired.txt unchanged: for each of the seeds 1-10 a base builds the named caches tmp/r6bc_seedN and the
# five levers reuse them (afterok chain per seed: launch WITHOUT --independent). Profile, code and folders as in
# jobs_20261111_ref.txt. Generated by gen_jobs_20261111.py.
#     bash studies/rhine2026/cluster/launch_rhine_batch.sh --jobs studies/rhine2026/cluster/jobs_20261111_paired.txt
#     bash studies/rhine2026/cluster/pack_results.sh --jobs studies/rhine2026/cluster/jobs_20261111_paired.txt
#
"""
(HERE / "jobs_20261111_paired.txt").write_text(HEAD_PAIRED + fmt(paired), encoding="utf-8", newline="\n")
print(f"jobs_20261111_ref.txt: {len(rows_ref)} lines ({len(rows_ref) - 1} runs and the cache builder); jobs_20261111_paired.txt: {len(paired)} runs")
print("runs that read the 2026 profile:", sum(1 for r in names if r.startswith(('2026_', 'wave_')) and r != control[0]) + len(paired))
